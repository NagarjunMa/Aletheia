import { describe, expect, it, vi } from "vitest";
import * as provenancePrompts from "@/lib/ai/prompts/atomic-provenance";
import * as applicationPrompts from "@/lib/ai/prompts/yc-application";
import savedBaseline from "../../../docs/evals/grounded-response-baseline.json";
import {
  lockedDiscourseFixtures,
  runDiscourseBaseline,
  compareDiscourseVariant,
} from "./grounded-discourse-report";

describe("offline discourse baseline and comparison", () => {
  it("pins exact configuration and origins without pretending fixtures were generated by a model", () => {
    const report = runDiscourseBaseline();
    expect(report.configuration).toMatchObject({
      outreachPromptVersion: "6.1.0",
      applicationPromptVersion: "yc-2.1.0",
      model: "claude-sonnet-4-6",
      providerCalls: 0,
      measuredProviderTokenUsage: null,
      configuredOutputTokenCeilings: {
        connection: 600,
        prose: 2400,
        applicationSingle: 1000,
        applicationFive: 8000,
      },
    });
    expect(
      report.expectedPropertyChecks.every((c) => c.expectedPropertiesMet),
    ).toBe(true);
    expect(report.rows.every((r) => r.violations.length === 0)).toBe(true);
    expect(
      report.rows.find((r) => r.category === "yc_application")!.origin,
    ).toBe("synthetic_reference_no_provider");
    expect(report.rows.find((r) => r.category === "cold_email")!.origin).toBe(
      "first_server_option_no_provider",
    );
    expect(runDiscourseBaseline()).toEqual(report);
    expect(report).toEqual(savedBaseline);
    const serialized = JSON.stringify(report);
    for (const value of [
      "supporting_excerpt",
      "synthetic-root",
      "fictional orchard sensor",
      "Synthetic",
      "The supplied context says",
      'body"',
      "source_id",
    ])
      expect(serialized).not.toContain(value);
  });
  it("refuses changed source/context/obligation contracts, missing cases and duplicate IDs", () => {
    const changed = structuredClone(lockedDiscourseFixtures);
    changed[0]!.targetRequired = false;
    expect(() => compareDiscourseVariant(changed)).toThrow(
      "Variant does not match the locked fixture contract",
    );
    expect(() =>
      compareDiscourseVariant(lockedDiscourseFixtures.slice(1)),
    ).toThrow();
    changed[0]!.id = changed[1]!.id;
    expect(() => compareDiscourseVariant(changed)).toThrow();
  });
  it("does not grant a go decision to unchanged template-heavy synthetic outputs", () => {
    const result = compareDiscourseVariant(lockedDiscourseFixtures);
    expect(result.decision).toBe("no_go");
    expect(result.diversityImproved).toBe(false);
  });
  it("can recognize structural improvement without dropping candidate or target claims", () => {
    const variant = structuredClone(lockedDiscourseFixtures);
    for (const sample of variant) {
      if (sample.expectedViolations.length) continue;
      const shouldSwap =
        sample.id.endsWith("library") ||
        sample.id.endsWith("bridge") ||
        /application-q[123]$/u.test(sample.id);
      const candidate = sample.claims.filter(
        (c) =>
          sample.sources.find((s) => s.id === c.source_id)?.scope ===
          "candidate",
      );
      if (shouldSwap && candidate.length === 2) {
        const [a, b] = candidate;
        sample.body = sample.body
          .replace(a!.text, "SYNTHETIC_SWAP_MARKER")
          .replace(b!.text, a!.text)
          .replace("SYNTHETIC_SWAP_MARKER", b!.text);
      }
    }
    const result = compareDiscourseVariant(variant);
    expect(result.safetyAndObligations).toBe(true);
    expect(result.negativeControlsPreserved).toBe(true);
    expect(result.diversityImproved).toBe(true);
    expect(result.decision).toBe("eligible_for_human_and_provider_review");
  });
});

it("runs the locked baseline without attempting external fetches", () => {
  const fetch = vi
    .spyOn(globalThis, "fetch")
    .mockRejectedValue(new Error("External I/O forbidden"));
  try {
    runDiscourseBaseline();
    expect(fetch).not.toHaveBeenCalled();
  } finally {
    fetch.mockRestore();
  }
});

it("ALE48-R1-003 fingerprints appended grounding and batch-specific system instructions", () => {
  const baseline = runDiscourseBaseline().configuration.promptFingerprint;
  const instruction = vi
    .spyOn(provenancePrompts, "getAtomicProvenanceInstructions")
    .mockReturnValue("Synthetic appended policy change");
  try {
    expect(runDiscourseBaseline().configuration.promptFingerprint).not.toBe(
      baseline,
    );
  } finally {
    instruction.mockRestore();
  }
  const build = applicationPrompts.buildYcApplicationPrompt;
  const batch = vi
    .spyOn(applicationPrompts, "buildYcApplicationPrompt")
    .mockImplementation((context) => {
      const result = build(context);
      return context.questions
        ? {
            ...result,
            systemPrompt:
              result.systemPrompt + " Synthetic batch policy change",
          }
        : result;
    });
  try {
    expect(runDiscourseBaseline().configuration.promptFingerprint).not.toBe(
      baseline,
    );
  } finally {
    batch.mockRestore();
  }
});
it("ALE48-R1-001 does not approve source-preserving variants padded with repeated greetings", () => {
  const variant = structuredClone(lockedDiscourseFixtures);
  for (const sample of variant) {
    if (sample.expectedViolations.length) continue;
    const shouldSwap =
      sample.id.endsWith("library") ||
      sample.id.endsWith("bridge") ||
      /application-q[123]$/u.test(sample.id);
    const candidates = sample.claims.filter(
      (c) =>
        sample.sources.find((s) => s.id === c.source_id)?.scope === "candidate",
    );
    if (shouldSwap && candidates.length === 2) {
      const [a, b] = candidates;
      sample.body = sample.body
        .replace(a!.text, "SYNTHETIC_SWAP_MARKER")
        .replace(b!.text, a!.text)
        .replace("SYNTHETIC_SWAP_MARKER", b!.text);
    }
  }
  const initial = variant.find(
    (f) => f.id === "synthetic-email-initial-outreach",
  )!;
  initial.body = initial.body.replace(
    "Hi there,\n\n",
    `Hi there,\n\n${"Hi there,\n\n".repeat(15)}`,
  );
  expect(compareDiscourseVariant(variant).decision).toBe("no_go");
});
